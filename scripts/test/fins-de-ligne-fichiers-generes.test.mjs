// @vitest-environment node
// Fichiers réécrits en LF par les compilations (Tauri, cargo) : sous Windows avec core.autocrlf=true, git les
// attendait en CRLF, les montrait « modifiés » sans différence et bloquait le changement de commit.
// .gitattributes les garde en LF, comme les compilations les écrivent.
import { describe, it, expect } from 'vitest';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const racine = fileURLToPath(new URL('../../', import.meta.url));
const git = (...args) => execFileSync('git', ['-C', racine, ...args], { encoding: 'utf8' });

const fichiers = [
  ...git('ls-files', '-z', '--', 'src-tauri/Cargo.toml', 'src-tauri/plugins/*/permissions/autogenerated/**', 'src-tauri/plugins/*/permissions/schemas/**').split('\0'),
].filter(Boolean);

describe('fichiers réécrits par les compilations', () => {
  it('le dépôt en porte (la liste ne doit jamais être vide)', () => {
    expect(fichiers.length).toBeGreaterThan(0);
  });

  it.each(fichiers)('%s : gardé en LF par .gitattributes', (fichier) => {
    expect(git('check-attr', 'eol', '--', fichier).trim()).toBe(`${fichier}: eol: lf`);
  });
});
